#!/usr/bin/env bash
# ReperioNet benchmark matrix: index-layout profiles x simulated device classes.
#
#   benchmarks/run-matrix.sh [DOCS] [ITERS]
#
# DOCS  documents per run (default 100000)
# ITERS timed iterations per query pattern (default 10)
#
# Device classes are simulated by restricting CPU affinity with taskset (the .NET runtime adapts
# Environment.ProcessorCount and all parallelism to the affinity mask). CPU clock speed cannot be
# changed from user space, which is a documented limitation: a real budget phone is slower per
# core and has slower flash storage than any class simulated here.
#
# Results are assembled into benchmarks/RESULTS.md.
set -euo pipefail

DOCS="${1:-100000}"
ITERS="${2:-10}"
ROOT="$(cd "$(dirname "$0")/.." && pwd)"
OUT="$ROOT/benchmarks/RESULTS.md"
TMP="/tmp/reperionet-matrix"
DLL="$ROOT/benchmarks/ReperioNet.Benchmark/bin/Release/net8.0/ReperioNet.Benchmark.dll"

TOTAL_CORES="$(nproc)"
DEVICES=(
  "desktop:0-$((TOTAL_CORES - 1))"
  "fast-phone (4 cores):0-3"
  "slow-phone (2 cores):0-1"
)
PROFILES=(full no-trigram compact smallest)

echo "building..."
dotnet build "$ROOT/benchmarks/ReperioNet.Benchmark" -c Release >/dev/null

rm -f "$TMP.summary.md" "$TMP.details.md"
mkdir -p "$(dirname "$TMP")"

run=0
total_runs=$(( ${#DEVICES[@]} * ${#PROFILES[@]} ))
for device in "${DEVICES[@]}"; do
  name="${device%%:*}"
  cpus="${device##*:}"
  for profile in "${PROFILES[@]}"; do
    run=$((run + 1))
    label="$name / $profile"
    echo
    echo "=== [$run/$total_runs] $label (cpus $cpus) ==="
    taskset -c "$cpus" dotnet "$DLL" \
      --docs "$DOCS" --iters "$ITERS" --profile "$profile" \
      --label "$label" --md "$TMP" \
      --db "/tmp/reperionet-bench/matrix.db" \
      | tail -12
  done
done

{
  echo "# ReperioNet benchmark results"
  echo
  echo "Generated by \`benchmarks/run-matrix.sh $DOCS $ITERS\` on $(date -u +"%Y-%m-%d %H:%M UTC")."
  echo
  echo "## Environment"
  echo
  echo "- CPU: $(grep -m1 'model name' /proc/cpuinfo | cut -d: -f2- | xargs) ($(nproc) cores, $(grep -m1 'cpu MHz' /proc/cpuinfo | cut -d: -f2- | xargs) MHz)"
  echo "- Memory: $(free -h | awk '/^Mem:/{print $2}') total"
  echo "- OS: $(uname -sr)"
  echo "- .NET: $(dotnet --version)"
  echo "- Documents per run: $DOCS email-like texts (en/de/fr 5:3:2, ~860 bytes average)"
  echo
  echo "Device classes are simulated via CPU affinity (taskset); per-core clock speed and storage"
  echo "speed cannot be throttled from user space, so phone-class numbers are optimistic — they"
  echo "model reduced parallelism, not slower silicon."
  echo
  echo "Profiles: \`full\` = trigram + stemming + phonetic + stored content; \`no-trigram\` drops"
  echo "substring recall; \`compact\` additionally stores no content copy (no snippets);"
  echo "\`smallest\` additionally drops phonetic codes and removes stop words from the stem stream."
  echo
  echo "## Summary"
  echo
  echo "| run | profile | cores | index docs/s | optimize | content | db size | db/content | needle p50 | common-term p50 | concurrent qps | add | peak mem | smoke |"
  echo "| --- | --- | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | ---: | --- |"
  cat "$TMP.summary.md"
  echo
  echo "## Per-run details"
  echo
  cat "$TMP.details.md"
} > "$OUT"

rm -f "$TMP.summary.md" "$TMP.details.md"
echo
echo "report written to $OUT"
